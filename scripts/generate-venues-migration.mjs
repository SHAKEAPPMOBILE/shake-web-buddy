#!/usr/bin/env node
/**
 * Generates supabase/migrations/<timestamp>_seed_venues.sql from src/data/venues.ts.
 * Reads CITY_VENUES (lunch_dinner), CITY_BARS (drinks), and CITY_BRUNCH_VENUES (brunch).
 *
 * Run:
 *   node scripts/generate-venues-migration.mjs
 *
 * Output is written to supabase/migrations/20260331220000_seed_venues.sql
 */

import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "src", "data", "venues.ts");
const OUT = path.join(ROOT, "supabase", "migrations", "20260331220000_seed_venues.sql");

// ── helpers ────────────────────────────────────────────────────────────────

function normalize(v) { return String(v ?? "").trim().replace(/\s+/g, " "); }

/** Extract the object literal assigned to `export const NAME` from TS source. */
function extractObjectLiteral(source, name) {
  const marker = `export const ${name}`;
  const mi = source.indexOf(marker);
  if (mi === -1) throw new Error(`Cannot find export const ${name}`);
  const ei = source.indexOf("=", mi);
  if (ei === -1) throw new Error(`Cannot find = for ${name}`);

  let depth = 0, inStr = false, strChar = "", i = ei + 1;
  let start = -1;
  while (i < source.length) {
    const c = source[i];
    if (!inStr) {
      if (c === "{") { if (depth === 0) start = i; depth++; }
      else if (c === "}") { depth--; if (depth === 0) return source.slice(start, i + 1); }
      else if (c === '"' || c === "'" || c === "`") { inStr = true; strChar = c; }
    } else {
      if (c === strChar && source[i - 1] !== "\\") inStr = false;
    }
    i++;
  }
  throw new Error(`Unbalanced braces for ${name}`);
}

/** Evaluate JS-compatible object literal (TS record) via vm. */
function evalRecord(src) {
  const code = `(${src})`;
  const ctx = vm.createContext({});
  return vm.runInContext(code, ctx);
}

/** Escape single-quotes for SQL string literals. */
function sq(s) { return normalize(s).replace(/'/g, "''"); }

// ── main ───────────────────────────────────────────────────────────────────

const source = await fs.readFile(SRC, "utf8");

const cityVenues      = evalRecord(extractObjectLiteral(source, "CITY_VENUES"));
const cityBars        = evalRecord(extractObjectLiteral(source, "CITY_BARS"));
const cityBrunchVenues = evalRecord(extractObjectLiteral(source, "CITY_BRUNCH_VENUES"));

/** @type {Array<{city,name,address,venue_type,sort_order}>} */
const rows = [];

// CITY_VENUES → lunch_dinner
for (const [city, venues] of Object.entries(cityVenues)) {
  venues.forEach((v, i) => {
    rows.push({ city, name: v.name, address: v.address || city, venue_type: "lunch_dinner", sort_order: i });
  });
}

// CITY_BARS → drinks
for (const [city, bars] of Object.entries(cityBars)) {
  bars.forEach((b, i) => {
    rows.push({ city, name: b.name, address: b.address || city, venue_type: "drinks", sort_order: i });
  });
}

// CITY_BRUNCH_VENUES → brunch (description goes into address as there is no separate column)
for (const [city, venues] of Object.entries(cityBrunchVenues)) {
  venues.forEach((v, i) => {
    rows.push({ city, name: v.name, address: v.description || city, venue_type: "brunch", sort_order: i });
  });
}

// ── build SQL ──────────────────────────────────────────────────────────────

const valueLines = rows.map(r =>
  `  ('${sq(r.city)}', '${sq(r.name)}', '${sq(r.address)}', '${sq(r.venue_type)}', ${r.sort_order}, true)`
);

const sql = `-- Seed venues from hardcoded app data (CITY_VENUES, CITY_BARS, CITY_BRUNCH_VENUES).
-- This migration makes venue data survive supabase db reset / push without needing
-- to run the manual seed script afterwards.
--
-- Generated by: node scripts/generate-venues-migration.mjs
-- Sources: src/data/venues.ts
-- Rows: ${rows.length} (${
  Object.values(cityVenues).flat().length
} lunch_dinner, ${
  Object.values(cityBars).flat().length
} drinks, ${
  Object.values(cityBrunchVenues).flat().length
} brunch)

-- Ensure idempotent inserts via unique constraint on (city, name, venue_type).
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'venues_city_name_venue_type_key'
      AND conrelid = 'public.venues'::regclass
  ) THEN
    ALTER TABLE public.venues
      ADD CONSTRAINT venues_city_name_venue_type_key
      UNIQUE (city, name, venue_type);
  END IF;
END $$;

INSERT INTO public.venues (city, name, address, venue_type, sort_order, is_active)
VALUES
${valueLines.join(",\n")}
ON CONFLICT (city, name, venue_type) DO NOTHING;
`;

await fs.writeFile(OUT, sql, "utf8");
console.log(`Written ${rows.length} rows → ${path.relative(ROOT, OUT)}`);
